"""DEVELOPMENT-ONLY one-command local Request Engine stack (compose.dev.yaml).

    uv run python scripts/dev/local_stack.py up      # build, migrate, roles, start, seed, worker
    uv run python scripts/dev/local_stack.py status  # health of every service
    uv run python scripts/dev/local_stack.py down [--volumes]

`up` stages: build image -> PostgreSQL 18 -> alembic upgrade head -> least-privilege
runtime logins -> runtime API + control plane + admin console + dev gateway ->
dev claim/organization/integration principal over public HTTP -> worker.
`--manual-claim` leaves the instance UNCLAIMED for the console setup wizard and
starts the worker later with `worker --principal-id <integration principal>`.

Secrets are generated per stack into the gitignored `.local-stack/<project>/` and
are dev-only. The tool refuses remote Docker hosts and binds ports to 127.0.0.1.

Pre-production rebaselines collapse the migration history; a dev database created
before one cannot upgrade across it. `up` detects that and asks you to recreate it
with `down --volumes` followed by `up`.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import secrets
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

import local_stack_seed

REPO = Path(__file__).resolve().parents[2]
COMPOSE_FILE = REPO / "compose.dev.yaml"
ROLES_SQL = REPO / "scripts" / "dev" / "init_local_runtime_roles.sql"
SERVICES = ("api", "control-plane", "console", "dev-gateway")
HEALTH_PATHS = {
    "api": ("RE_DEV_API_PORT", "/health/ready"),
    "control-plane": ("RE_DEV_CONTROL_PORT", "/health/ready"),
    "console": ("RE_DEV_CONSOLE_PORT", "/health/ready"),
    "dev-gateway": ("RE_DEV_GATEWAY_PORT", "/health"),
}
_SECRET_KEYS = (
    "RE_DEV_POSTGRES_PASSWORD",
    "RE_DEV_APP_PASSWORD",
    "RE_DEV_READ_PASSWORD",
    "RE_DEV_CONTROL_PASSWORD",
    "RE_DEV_WORKER_PASSWORD",
    "RE_DEV_APPOINTMENT_SIGNING_KEY",
    "RE_DEV_FINGERPRINT_KEY",
    "RE_DEV_WEBAUTHN_DECOY_KEY",
    "RE_DEV_CONSOLE_SESSION_SECRET",
)


class Stack:
    def __init__(self, args: argparse.Namespace) -> None:
        self.args = args
        self.project: str = args.project
        self.state = REPO / ".local-stack" / self.project
        self.env_file = self.state / "dev.env"
        self.credentials = self.state / "credentials.json"
        self.tls = self.state / "tls"

    # -- configuration ---------------------------------------------------------
    def env(self) -> dict[str, str]:
        if not self.env_file.exists():
            return {}
        lines = self.env_file.read_text().splitlines()
        pairs = (line.split("=", 1) for line in lines if line and not line.startswith("#"))
        return {key: value for key, value in pairs}

    def write_env(self, values: dict[str, str]) -> None:
        self.state.mkdir(parents=True, exist_ok=True)
        lines = ["# DEVELOPMENT ONLY - generated by scripts/dev/local_stack.py; never reuse"]
        lines += [f"{key}={value}" for key, value in sorted(values.items())]
        self.env_file.write_text("\n".join(lines[1:]) + "\n")
        (self.state / "README.txt").write_text(lines[0] + "\n")

    def configure(self) -> dict[str, str]:
        values = self.env()
        for key in _SECRET_KEYS:
            values.setdefault(key, f"devonly{secrets.token_urlsafe(32)}")
        for key, attribute in (
            ("RE_DEV_API_PORT", "api_port"),
            ("RE_DEV_CONTROL_PORT", "control_port"),
            ("RE_DEV_CONSOLE_PORT", "console_port"),
            ("RE_DEV_GATEWAY_PORT", "gateway_port"),
        ):
            values[key] = str(getattr(self.args, attribute))
        values["RE_DEV_TLS_DIR"] = self.tls.as_posix()
        self.write_env(values)
        _ensure_tls(self.tls)
        return values

    # -- docker ------------------------------------------------------------------
    def compose(self, *arguments: str, stdin: str | None = None, capture: bool = False) -> str:
        command = ["docker", "compose", "-p", self.project, "-f", str(COMPOSE_FILE)]
        command += ["--env-file", str(self.env_file), *arguments]
        result = subprocess.run(
            command, cwd=REPO, input=stdin, text=True, capture_output=capture, check=False
        )
        if result.returncode != 0:
            detail = (result.stderr or "").strip() if capture else ""
            raise SystemExit(f"docker compose {' '.join(arguments[:2])} failed {detail}")
        return result.stdout or ""

    def psql(self, sql: str) -> str:
        return self.compose(
            "exec", "-T", "postgres", "psql", "-U", "postgres", "-d", "request_engine",
            "-v", "ON_ERROR_STOP=1", "-tA", stdin=sql, capture=True,
        )  # fmt: skip

    def require_known_revision(self) -> None:
        """Fail early when the dev volume predates a pre-production rebaseline.

        A database created from a collapsed migration history records a revision
        that no longer exists in migrations/versions and cannot be upgraded.
        """
        current = self.psql(
            "SELECT CASE WHEN to_regclass('public.alembic_version') IS NULL THEN '' "
            "ELSE (SELECT string_agg(version_num, ',') FROM public.alembic_version) END;"
        ).strip()
        if not current:
            return
        unknown = set(current.split(",")) - _repository_revisions()
        if unknown:
            raise SystemExit(
                f"dev database is at {', '.join(sorted(unknown))}, which is not in "
                "migrations/versions (the history was rebaselined). Recreate it: "
                "scripts/dev/local_stack.ps1 down --volumes, then up."
            )

    # -- lifecycle ---------------------------------------------------------------
    def up(self) -> None:
        values = self.configure()
        self.compose("--profile", "setup", "build", "migrate")
        self.compose("up", "-d", "--wait", "postgres")
        self.require_known_revision()
        self.compose("--profile", "setup", "run", "--rm", "migrate")
        self.provision_roles(values)
        ids = self.psql(
            "SELECT built_in_native_authority_id || ',' || built_in_workload_authority_id "
            "FROM request_engine.platform_instance WHERE singleton_key = 1;"
        ).strip()
        native, workload = ids.split(",")
        values["RE_DEV_NATIVE_AUTHORITY_ID"] = native
        values["RE_DEV_WORKLOAD_AUTHORITY_ID"] = workload
        self.write_env(values)
        self.compose("up", "-d", "--wait", "--wait-timeout", "180", *SERVICES)
        principal = None if self.args.manual_claim else self.dev_world()
        if principal:
            self.start_worker(values, principal)
        self.status()

    def provision_roles(self, values: dict[str, str]) -> None:
        sql = ROLES_SQL.read_text()
        sql += "\nDO $do$ BEGIN\n"
        sql += "  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 're_dev_worker') THEN\n"
        sql += "    CREATE ROLE re_dev_worker LOGIN;\n  END IF;\nEND $do$;\n"
        sql += "GRANT request_engine_worker TO re_dev_worker;\n"
        for role, key in (
            ("re_dev_app", "RE_DEV_APP_PASSWORD"),
            ("re_dev_read", "RE_DEV_READ_PASSWORD"),
            ("re_dev_control", "RE_DEV_CONTROL_PASSWORD"),
            ("re_dev_worker", "RE_DEV_WORKER_PASSWORD"),
        ):
            sql += f"ALTER ROLE {role} PASSWORD '{values[key]}';\n"
        self.psql(sql)

    def dev_world(self) -> str | None:
        control = f"http://127.0.0.1:{self.args.control_port}"
        if local_stack_seed.setup_required(control):
            world = local_stack_seed.seed(
                control_url=control,
                api_url=f"http://127.0.0.1:{self.args.api_port}",
                console_origin=f"http://localhost:{self.args.console_port}",
            )
            self.credentials.write_text(json.dumps(world, indent=2) + "\n")
            print(f"dev instance claimed; generated dev logins: {self.credentials}")
        if not self.credentials.exists():
            print("instance already claimed without a local dev world; start the worker with")
            print("  local_stack.py worker --principal-id <activated integration principal id>")
            return None
        return str(json.loads(self.credentials.read_text())["worker_principal_id"])

    def start_worker(self, values: dict[str, str], principal: str) -> None:
        values["RE_DEV_WORKER_PRINCIPAL_ID"] = principal
        self.write_env(values)
        self.compose("--profile", "worker", "up", "-d", "worker")

    def status(self) -> None:
        values = self.env()
        for service, (port_key, path) in HEALTH_PATHS.items():
            port = values.get(port_key, "?")
            print(f"{service:14} http://localhost:{port}{path} -> {_probe(port, path)}")
        print(f"{'worker':14} {self.worker_state()}")
        console = values.get("RE_DEV_CONSOLE_PORT", "?")
        print(f"open the console at http://localhost:{console} (use localhost for passkeys)")

    def worker_state(self) -> str:
        cid = self.compose("--profile", "worker", "ps", "-aq", "worker", capture=True).strip()
        if not cid:
            return "not started (needs an integration principal)"
        inspected = subprocess.run(
            ["docker", "inspect", "-f", "{{.State.Status}} restarts={{.RestartCount}}", cid],
            text=True,
            capture_output=True,
            check=False,
        )
        return inspected.stdout.strip() or "unknown"

    def down(self) -> None:
        arguments = ["--profile", "setup", "--profile", "worker", "down", "--remove-orphans"]
        self.compose(*arguments, *(["--volumes"] if self.args.volumes else []))
        if self.args.volumes:
            shutil.rmtree(self.state, ignore_errors=True)


def _probe(port: str, path: str) -> str:
    try:
        with urllib.request.urlopen(f"http://127.0.0.1:{port}{path}", timeout=3) as response:
            return f"HTTP {response.status}"
    except Exception as exc:  # status report only
        return f"DOWN ({type(exc).__name__})"


def _repository_revisions() -> set[str]:
    pattern = re.compile(r'^revision: str = "([^"]+)"$', re.MULTILINE)
    return {
        match.group(1)
        for path in (REPO / "migrations" / "versions").glob("*.py")
        for match in pattern.finditer(path.read_text(encoding="utf-8"))
    }


def _ensure_tls(directory: Path) -> None:
    """Generate a throwaway dev CA and a dev-gateway leaf certificate once."""

    if (directory / "dev-gateway.key").exists():
        return
    from cryptography import x509
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.x509.oid import NameOID

    directory.mkdir(parents=True, exist_ok=True)
    now = dt.datetime.now(dt.UTC)

    def name(value: str) -> x509.Name:
        return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, value)])

    def builder(
        subject: str, issuer: str, key: ec.EllipticCurvePrivateKey
    ) -> x509.CertificateBuilder:
        return (
            x509.CertificateBuilder()
            .subject_name(name(subject))
            .issuer_name(name(issuer))
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(now - dt.timedelta(minutes=5))
            .not_valid_after(now + dt.timedelta(days=365))
        )

    ca_key = ec.generate_private_key(ec.SECP256R1())
    ca = (
        builder("Request Engine DEV-ONLY local CA", "Request Engine DEV-ONLY local CA", ca_key)
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=False,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .sign(ca_key, hashes.SHA256())
    )
    leaf_key = ec.generate_private_key(ec.SECP256R1())
    leaf = (
        builder("dev-gateway", "Request Engine DEV-ONLY local CA", leaf_key)
        .add_extension(x509.SubjectAlternativeName([x509.DNSName("dev-gateway")]), critical=False)
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .sign(ca_key, hashes.SHA256())
    )
    pem = serialization.Encoding.PEM
    (directory / "dev-ca.crt").write_bytes(ca.public_bytes(pem))
    (directory / "dev-gateway.crt").write_bytes(leaf.public_bytes(pem))
    (directory / "dev-gateway.key").write_bytes(
        leaf_key.private_bytes(pem, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())
    )


def _require_local_docker() -> None:
    if shutil.which("docker") is None:
        raise SystemExit("docker CLI not found on PATH")
    endpoint = (
        os.environ.get("DOCKER_HOST")
        or subprocess.run(
            ["docker", "context", "inspect", "-f", "{{.Endpoints.docker.Host}}"],
            text=True,
            capture_output=True,
            check=False,
        ).stdout.strip()
    )
    if not endpoint.startswith(("npipe://", "unix://")):
        raise SystemExit(f"refusing Docker endpoint {endpoint!r}: the dev stack is local-only")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("command", choices=("up", "down", "status", "worker"))
    parser.add_argument("--project", default="request-engine-dev")
    parser.add_argument("--api-port", type=int, default=58100)
    parser.add_argument("--control-port", type=int, default=58101)
    parser.add_argument("--console-port", type=int, default=58102)
    parser.add_argument("--gateway-port", type=int, default=58190)
    parser.add_argument("--manual-claim", action="store_true", help="leave setup to the console")
    parser.add_argument("--principal-id", help="worker: activated integration principal id")
    parser.add_argument("--volumes", action="store_true", help="down: also delete data/secrets")
    args = parser.parse_args()
    _require_local_docker()
    stack = Stack(args)
    if args.command != "up" and not stack.env_file.exists():
        raise SystemExit(f"no local stack named {args.project!r}; run 'up' first")
    if args.command == "up":
        stack.up()
    elif args.command == "down":
        stack.down()
    elif args.command == "worker":
        if not args.principal_id:
            raise SystemExit("worker requires --principal-id")
        stack.start_worker(stack.env(), args.principal_id)
        stack.status()
    else:
        stack.status()


if __name__ == "__main__":
    sys.exit(main())
